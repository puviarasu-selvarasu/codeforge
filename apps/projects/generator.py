def sanitize_project_name(name):
    """Convert a string to a valid Python identifier."""
    # Remove invalid characters
    name = re.sub(r'[^a-zA-Z0-9_]', '_', name)
    # Remove leading underscores or digits
    name = re.sub(r'^[^a-zA-Z]+', '', name)
    # If empty, use default
    if not name or name == 'config':
        return 'django_project'
    return name

def apply_template_replacements(template, project_name):
    """Replace __PROJECT_NAME__ in all file paths and contents."""
    for file_spec in template["files"]:
        # Replace in path
        file_spec["path"] = file_spec["path"].replace("__PROJECT_NAME__", project_name)
        # Replace in content
        file_spec["content"] = file_spec["content"].replace("__PROJECT_NAME__", project_name)
    # Also update the project_name field itself
    template["project_name"] = project_name
    return template

def generate_plan(user_prompt, context_chunks=None):
    prompt_lower = user_prompt.lower()
    detected_framework = None

    if "django" in prompt_lower:
        detected_framework = "django"
    elif "laravel" in prompt_lower:
        detected_framework = "laravel"
    elif "spring" in prompt_lower or "springboot" in prompt_lower:
        detected_framework = "springboot"
    elif "flask" in prompt_lower:
        detected_framework = "flask"
    elif "react" in prompt_lower:
        detected_framework = "react"
    elif "pygame" in prompt_lower or "game" in prompt_lower:
        detected_framework = "pygame"
    else:
        detected_framework = "python"

    if detected_framework in FALLBACK_TEMPLATES:
        template = FALLBACK_TEMPLATES[detected_framework].copy()

        # Generate a clean project name from the user prompt
        words = user_prompt.split()[:4]
        raw_name = "_".join([w.lower() for w in words if w.isalnum()])
        project_name = sanitize_project_name(raw_name)

        # Apply replacements
        apply_template_replacements(template, project_name)

        logger.info(f"Generated plan for project: {project_name} (framework: {detected_framework})")
        return template

    # Fallback to LLM (if needed)
    try:
        prompt = f"User request: {user_prompt}\n"
        if context_chunks:
            prompt += "\nRelevant context:\n" + "\n\n".join(context_chunks)
        prompt += "\n\nGenerate a complete project plan as JSON."

        full_response = ""
        for chunk in llm.generate_stream(prompt, system_override=SYSTEM_PROMPT):
            full_response += chunk

        cleaned = re.sub(r'```json\s*', '', full_response)
        cleaned = re.sub(r'```\s*', '', cleaned)
        start = cleaned.find('{')
        end = cleaned.rfind('}') + 1
        if start != -1 and end > start:
            json_str = cleaned[start:end]
            plan = json.loads(json_str)
            if 'files' in plan and 'commands' in plan and len(plan.get('files', [])) >= 3:
                # Sanitize and replace project name if present
                if 'project_name' in plan:
                    plan['project_name'] = sanitize_project_name(plan['project_name'])
                return plan
    except Exception as e:
        logger.error(f"LLM plan generation failed: {e}")

    # Ultimate fallback – use python template
    python_template = FALLBACK_TEMPLATES.get("python", {}).copy()
    if python_template:
        project_name = sanitize_project_name("python_script")
        apply_template_replacements(python_template, project_name)
        return python_template
    else:
        # Hardcoded fallback
        return {
            "project_name": "project",
            "framework": "python",
            "summary": "A simple Python project.",
            "files": [{"path": "main.py", "content": "print('Hello World')"}],
            "commands": ["python main.py"]
        }

