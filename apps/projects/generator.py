SCRIPT_SYSTEM_PROMPT = """
You are CodeForge, a senior software engineer. The user wants a simple script or code snippet.
Provide only the code, without any extra text or explanation.
If the user asks for a specific language, use that language. Otherwise, use Python.
Keep the code clean and functional.
"""

def generate_script(user_prompt, context_chunks=None):
    """Generate a single-file script using the LLM."""
    prompt = f"Write code for: {user_prompt}"
    if context_chunks:
        prompt += "\n\nRelevant context:\n" + "\n\n".join(context_chunks)
    response = ""
    for chunk in llm.generate_stream(prompt, system_override=SCRIPT_SYSTEM_PROMPT):
        response += chunk
    import re
    match = re.search(r'```(\w+)?\n(.*?)```', response, re.DOTALL)
    if match:
        return match.group(2).strip()
    return response.strip()